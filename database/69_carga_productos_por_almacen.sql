       count(*) filter (where u.codigo = 'UND') as en_unidad, count(*) filter (where u.codigo <> 'UND') as otra_unidad
  from producto_almacen pa join almacen a on a.id = pa.almacen_id
  join producto p on p.id = pa.producto_id join unidad_medida u on u.id = p.unidad_id
 group by a.nombre order by a.nombre;
